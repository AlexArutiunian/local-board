
from __future__ import annotations

from typing import Any

ASSESSMENT_VERSION = 1


def _single(qid: str, prompt: str, options: list[str], answer: int, why: str) -> dict[str, Any]:
    return {
        "id": qid,
        "type": "single",
        "prompt": prompt,
        "options": options,
        "answer": answer,
        "rubric": [why],
    }


def _multiple(
    qid: str,
    prompt: str,
    options: list[str],
    answer: list[int],
    why: str,
) -> dict[str, Any]:
    return {
        "id": qid,
        "type": "multiple",
        "prompt": prompt,
        "options": options,
        "answer": answer,
        "rubric": [why],
    }


def _manual(
    qid: str,
    kind: str,
    prompt: str,
    rubric: list[str],
    *,
    starter: str | None = None,
) -> dict[str, Any]:
    question: dict[str, Any] = {
        "id": qid,
        "type": kind,
        "prompt": prompt,
        "rubric": rubric,
    }
    if starter:
        question["starter"] = starter
    return question


