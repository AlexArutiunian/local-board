QUESTION_INDEX: dict[str, dict[str, Any]] = {
    question["id"]: question
    for block in ASSESSMENT_BLOCKS
    for question in block["questions"]
}


def public_assessment() -> dict[str, Any]:
    blocks: list[dict[str, Any]] = []
    for block in ASSESSMENT_BLOCKS:
        questions: list[dict[str, Any]] = []
        for source in block["questions"]:
            question = {
                key: value
                for key, value in source.items()
                if key not in {"answer", "rubric"}
            }
            questions.append(question)
        blocks.append(
            {
                "id": block["id"],
                "title": block["title"],
                "description": block["description"],
                "questions": questions,
            }
        )
    return {
        "version": ASSESSMENT_VERSION,
        "title": "Middle ML/CV Engineer Assessment",
        "blocks": blocks,
        "question_count": len(QUESTION_INDEX),
    }


def is_objective(question: dict[str, Any]) -> bool:
    return question["type"] in {"single", "multiple"}


def objective_answer_is_correct(question: dict[str, Any], answer: Any) -> bool:
    if question["type"] == "single":
        return isinstance(answer, int) and not isinstance(answer, bool) and answer == question["answer"]
    if question["type"] == "multiple":
        if not isinstance(answer, list) or any(
            isinstance(item, bool) or not isinstance(item, int) for item in answer
        ):
            return False
        return sorted(set(answer)) == sorted(question["answer"])
    raise ValueError("question requires manual review")


def review_questions() -> list[dict[str, Any]]:
    result: list[dict[str, Any]] = []
    for block in ASSESSMENT_BLOCKS:
        for question in block["questions"]:
            result.append(
                {
                    "id": question["id"],
                    "block_id": block["id"],
                    "block_title": block["title"],
                    "type": question["type"],
                    "prompt": question["prompt"],
                    "rubric": question["rubric"],
                    **({"options": question["options"]} if "options" in question else {}),
                    **({"answer": question["answer"]} if is_objective(question) else {}),
                }
            )
    return result
